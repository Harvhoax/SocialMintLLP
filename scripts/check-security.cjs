const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const compiled = ts.transpileModule(fs.readFileSync('src/lib/brief.ts', 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const api = {};
new Function('exports','require',compiled)(api,require);
const valid = {name:' Tushar Singh ',contact:' info@socialmintstudio.com ',message:'A real project enquiry.',services:['Reels']};
assert.equal(api.briefSchema.parse(valid).name,'Tushar Singh');
assert.equal(api.briefSchema.parse(valid).contact,'info@socialmintstudio.com');
for (const contact of ['----------','() () () ()','+123','1234567890123456','a@','\r\nBcc:evil@example.com']) assert.equal(api.briefSchema.safeParse({...valid,contact}).success,false);
for (const contact of ['+91 93213 88129','9321388129','person@example.com']) assert.equal(api.briefSchema.safeParse({...valid,contact}).success,true);
for (const overrides of [{name:'x'}, {name:'x'.repeat(101)}, {name:'Name\r\nBcc: injected'}, {message:'   '}, {message:'x'.repeat(3001)}, {services:Array(7).fill('Reels')}]) assert.equal(api.briefSchema.safeParse({...valid,...overrides}).success,false);
const links=api.enquiryLinks(api.briefSchema.parse(valid),'info@socialmintstudio.com','+919321388129');
assert.equal(new URL(links.whatsapp).hostname,'wa.me');
assert.equal(new URL(links.whatsapp).pathname,'/919321388129');
assert.equal(new URL(links.whatsapp).searchParams.get('text'),links.body);
assert.equal(new URL(links.email).searchParams.get('body'),links.body);
const long=api.enquiryLinks({...valid,message:'🎥'.repeat(1400)},'info@socialmintstudio.com','+919321388129');
assert.equal(long.copyForEmail,true);assert.equal(long.copyForWhatsapp,true);
assert.equal(long.whatsapp,'https://wa.me/919321388129');
assert.ok(long.body.includes('🎥'.repeat(1400)));
const hostile=api.enquiryLinks({...valid,message:'Hello &bcc=attacker@example.com #test <script>alert(1)</script>'},'info@socialmintstudio.com','+919321388129');
assert.equal(new URL(hostile.email).searchParams.has('bcc'),false);
assert.ok(new URL(hostile.email).searchParams.get('body').includes('&bcc='));
const contact=fs.readFileSync('src/components/ContactBrief.tsx','utf8');
assert.ok(!contact.includes('fetch('));
assert.ok(!contact.includes('localStorage.setItem'));
const headers=JSON.parse(fs.readFileSync('vercel.json','utf8')).headers[0].headers;
assert.equal(headers.find(h=>h.key==='X-Frame-Options').value,'DENY');
assert.match(headers.find(h=>h.key==='Content-Security-Policy').value,/frame-ancestors 'none'/);
console.log('Security checks passed: input limits, phone/email parsing, normalization, safe enquiry links, long-message fallbacks and framing policy.');
